def reference_answer(question,show_sources=False):
    text=str(question).casefold().replace('ё','е')
    if not any(w in text for w in ('что такое','слоист','слойчат','признак','отлич','сравни','расскажи')):return ''
    found=[];occupied=[]
    for profile in sorted(PROFILES,key=lambda p:-len(p[0])):
        # Allow normal Russian inflections; require every diagnostic name word.
        stems=[w[:max(5,len(w)-2)] for w in profile[0].casefold().replace('ё','е').split()]
        pattern=r'(?<![а-я])'+r'\s+'.join(re.escape(stem)+r'[а-я]*' for stem in stems)+r'(?![а-я-])'
        matches=list(re.finditer(pattern,text))
        for match in matches:
            a,b=match.span()
            if not any(a<d and b>c for c,d in occupied):
                occupied.append((a,b));found.append(profile);break
    if not found:
        if 'виды слоист' in text or 'типы слоист' in text:
            return 'Справочник слоистости CV-1:\n'+'\n'.join(p[0] for p in PROFILES)+'\n\nНаличие термина в справочнике не означает, что визуальный класс уже обучен.'
        return ''
    answer='\n\n'.join(p[0]+'\n'+p[1]+'\n'+p[2] for p in found[:3])
    if show_sources:
        answer+='\n\nИсточники: '+'; '.join(SOURCES[k][0]+' — '+SOURCES[k][1] for k in dict.fromkeys(p[3] for p in found[:3]))
    return answer
